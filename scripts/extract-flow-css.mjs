/**
 * Regenerates src/components/NodeNetworkStates/flowBaseCss.ts.
 *
 * React Flow's stylesheet cannot simply be imported: the plugin build inlines
 * every imported stylesheet into main.js and injects it into the document at
 * load time, and its `.react-flow__*` class names are the same ones Headlamp's
 * own resource Map uses — so a plain import restyles Headlamp's Map from every
 * page of the app. Importing it with Vite's `?raw` suffix does not help either:
 * the file still gets picked up and injected as CSS, while the import itself
 * yields an empty string.
 *
 * So the stylesheet is vendored as a TypeScript string instead. Nothing imports
 * a `.css` file, nothing is injected globally, and scopedFlowStyles.ts prefixes
 * every selector at runtime.
 *
 * Re-run after upgrading @xyflow/react:
 *
 *   node scripts/extract-flow-css.mjs
 */
import { readFileSync, writeFileSync } from 'node:fs';

const SOURCE = 'node_modules/@xyflow/react/dist/base.css';
const OUT = 'src/components/NodeNetworkStates/flowBaseCss.ts';

const version = JSON.parse(
  readFileSync('node_modules/@xyflow/react/package.json', 'utf8')
).version;

const css = readFileSync(SOURCE, 'utf8').trim();

if (!css.includes('.react-flow__node')) {
  console.error(`${SOURCE} does not look like React Flow's stylesheet`);
  process.exit(1);
}

// Escape only what a template literal can misread.
const escaped = css.replace(/\\/g, '\\\\').replace(/`/g, '\\`').replace(/\$\{/g, '\\${');

writeFileSync(
  OUT,
  `/**
 * React Flow's base stylesheet, vendored as a string.
 *
 * Generated by scripts/extract-flow-css.mjs from @xyflow/react ${version} —
 * do not edit by hand. See that script for why this is not a CSS import.
 *
 * Consumed by scopedFlowStyles.ts, which confines every selector to the
 * plugin's own canvas so Headlamp's resource Map is left untouched.
 */
export const FLOW_BASE_CSS = \`${escaped}\`;
`
);

console.log(`Wrote ${css.length} bytes of @xyflow/react ${version} CSS to ${OUT}`);
